function layerDef(handle: string, name: string, color: number, ltype: string): string[] {
  return ["0", "LAYER", "5", handle, "2", name, "70", "0", "62", String(color), "6", ltype];
}

function lineEnt(
  handle: string,
  layer: string,
  x1: number,
  y1: number,
  x2: number,
  y2: number,
): string[] {
  return [
    "0",
    "LINE",
    "5",
    handle,
    "8",
    layer,
    "10",
    String(x1),
    "20",
    String(y1),
    "11",
    String(x2),
    "21",
    String(y2),
  ];
}

function circleEnt(handle: string, layer: string, cx: number, cy: number, r: number): string[] {
  return [
    "0",
    "CIRCLE",
    "5",
    handle,
    "8",
    layer,
    "10",
    String(cx),
    "20",
    String(cy),
    "40",
    String(r),
  ];
}

function arcEnt(
  handle: string,
  layer: string,
  cx: number,
  cy: number,
  r: number,
  startDeg: number,
  endDeg: number,
): string[] {
  return [
    "0",
    "ARC",
    "5",
    handle,
    "8",
    layer,
    "10",
    String(cx),
    "20",
    String(cy),
    "40",
    String(r),
    "50",
    String(startDeg),
    "51",
    String(endDeg),
  ];
}

function textEnt(
  handle: string,
  layer: string,
  x: number,
  y: number,
  height: number,
  value: string,
): string[] {
  return [
    "0",
    "TEXT",
    "5",
    handle,
    "8",
    layer,
    "10",
    String(x),
    "20",
    String(y),
    "40",
    String(height),
    "1",
    value,
  ];
}
